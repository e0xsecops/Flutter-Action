/// The bottom navigation labels fit, in every language, as rendered.
///
/// **The defect this holds.** On the emulator, the Japanese Intelligence tab
/// read 「インテリジ…」: eight full-width characters in a slot that holds six.
/// Nothing caught it because nothing could — `flutter test` shapes every glyph
/// with the FlutterTest font, in which a Latin letter, a Thai tone mark and a
/// kanji are all one em wide, so "does this label fit?" had no true answer in
/// a widget test. A character budget would not have been an answer either:
/// Thai fits at thirteen code points where Japanese does not fit at eight.
///
/// **How it measures.** The production shell is built through the production
/// router, and the text is shaped with the fonts the QA device actually draws
/// it with: Roboto for Latin and Cyrillic, and the Noto faces Android falls
/// back to for Arabic, Bengali, Devanagari, Thai and the CJK scripts. They are
/// subsets under `test/fonts/`, regenerated by `tool/qa_fonts/subset_qa_fonts.py`.
/// The only thing the test changes about the theme is the font family list;
/// sizes, weights, paddings and the bar's geometry are the shipped ones.
///
/// **What "fits" means here.** The label's own `RenderParagraph` reports
/// whether it exceeded its one allowed line — the exact condition under which
/// the framework draws the ellipsis. Nothing is estimated.
